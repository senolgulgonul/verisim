    // ---- send one character to the SoC's UART receiver ----
    task uart_send(input [7:0] c);
        integer b;
        begin
            uart_rx = 1'b0;                     // start bit
            #(BIT_NS);
            for (b = 0; b < 8; b = b + 1) begin
                uart_rx = c[b];
                #(BIT_NS);
            end
            uart_rx = 1'b1;                     // stop bit
            #(BIT_NS);
        end
    endtask

