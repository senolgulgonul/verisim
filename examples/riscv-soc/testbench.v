// =============================================================================
//  testbench.v  --  SoC demo: C firmware, UART, GPIO, timer, interrupts
// -----------------------------------------------------------------------------
//  The firmware (C, built with -march=rv32imc_zicsr, sources in firmware/) is
//  embedded below as 32-bit words. It
//    - prints a banner and the primes below 50 over the UART
//    - counts timer interrupts and shows the count on the GPIO outputs ("LEDs")
//    - receives characters through the UART RX interrupt and upper-cases them
//    - counts button presses through the GPIO interrupt
//    - checks its own results, prints "ALL OK" and sends EOT (0x04)
//
//  The testbench
//    - decodes the UART TX line and prints every character to the console
//    - sends "abc" to the UART RX line and presses the button (gpio_in[0]) once
//    - stops at EOT and reports PASS if the last line was "ALL OK"
//
//  The UART runs at 8 clock cycles per bit here to keep the simulation short.
//  Only top-level signals are dumped to keep the VCD small.
//
//  Icarus:  iverilog -g2005 -o sim design.v testbench.v && vvp sim
// =============================================================================
